// Compiles the physical models in src/engine/faust/dsp/*.dsp to WebAssembly with the Faust compiler (libfaust built
// for WebAssembly, so no system install is needed) and writes one TypeScript module per model to src/engine/faust/gen.
// Usage: npm run faust
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { FaustCompiler, LibFaust, instantiateFaustModuleFromFile } from '@grame/faustwasm/dist/esm/index.js';

/** Must match MAX_PARAMS in src/engine/faust/processor.ts: each control becomes one AudioParam. */
const MAX_PARAMS = 24;
const DSP_DIR = 'src/engine/faust/dsp';
const GEN_DIR = 'src/engine/faust/gen';

const faustModule = await instantiateFaustModuleFromFile('node_modules/@grame/faustwasm/libfaust-wasm/libfaust-wasm.js');
const compiler = new FaustCompiler(new LibFaust(faustModule));
console.log(`Faust ${compiler.version()}`);

/** Every input control in the UI tree, in order. */
function controls(items, out = []) {
  for (const it of items) {
    if (it.items) controls(it.items, out);
    else if (['hslider', 'vslider', 'nentry', 'button', 'checkbox'].includes(it.type)) {
      out.push({ label: it.label, index: it.index, init: it.init ?? 0 });
    }
  }
  return out;
}

let failed = false;
for (const file of readdirSync(DSP_DIR).filter((f) => f.endsWith('.dsp')).sort()) {
  const name = file.replace(/\.dsp$/, '');
  const code = readFileSync(join(DSP_DIR, file), 'utf8');
  const factory = await compiler.createMonoDSPFactory(name, code, '-ftz 2');
  if (!factory) {
    console.error(`FAIL ${file}: ${compiler.getErrorMessage()}`);
    failed = true;
    continue;
  }
  const meta = JSON.parse(factory.json);
  const params = controls(meta.ui);
  if (params.length > MAX_PARAMS) {
    console.error(`FAIL ${file}: ${params.length} controls, at most ${MAX_PARAMS}`);
    failed = true;
    continue;
  }
  const wasm = Buffer.from(factory.code).toString('base64');
  const body = { size: meta.size, outputs: meta.outputs, params, wasm };
  writeFileSync(
    join(GEN_DIR, `${name}.ts`),
    `// Generated by scripts/build-faust.mjs from dsp/${file}. Do not edit; run npm run faust.\n` +
      `import type { FaustModel } from '../types';\n\n` +
      `const model: FaustModel = ${JSON.stringify(body)};\nexport default model;\n`,
  );
  console.log(`${name}: ${params.length} controls, ${(factory.code.length / 1024).toFixed(1)} KB`);
}
process.exit(failed ? 1 : 0);
